/**
 * The component registry: every building block an architecture can contain.
 *
 * One catalog feeds the whole app — the Architecture Canvas palette, the call
 * simulator, the validator, the scaling model, the cost engine and the
 * inspector panels all read the same `ComponentSpec`s. Capacity, latency and
 * price figures are SIMULATION ASSUMPTIONS (order-of-magnitude plausible,
 * editable, and labelled as such in the UI).
 */

