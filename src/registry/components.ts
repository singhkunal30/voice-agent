// -- failure mode helpers ----------------------------------------------------

const fm = (partial: Omit<FailureMode, 'id'> & { id?: string }): FailureMode => ({
  id: partial.id ?? `${partial.kind}-${partial.name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
  ...partial,
})

const providerOutage = (what: string, mitigations: string[]): FailureMode =>
  fm({
    kind: 'unavailable',
    name: `${what} unavailable`,
    callerImpact: 'The call goes silent or dies mid-sentence; new calls fail to start.',
    signal: 'Connection refused / 5xx spike; success rate drops to zero for this dependency.',
    mitigations,
    defaultProbability: 0.02,
    fatal: true,
  })

const timeoutMode = (what: string, impact: string): FailureMode =>
  fm({
    kind: 'timeout',
    name: `${what} timeout`,
    callerImpact: impact,
    signal: 'p99 latency hits the client timeout; requests complete but too late to be useful.',
    mitigations: ['Explicit timeout tuned to the voice budget', 'Retry with backoff (idempotent ops only)', 'Fallback path or spoken filler'],
    defaultProbability: 0.03,
  })

const rateLimit = (what: string): FailureMode =>
  fm({
    kind: 'rate-limit',
    name: `${what} rate limit`,
    callerImpact: 'New calls or new turns fail while existing ones continue; bursty traffic is punished.',
    signal: '429 responses; provider quota dashboard at 100%.',
    mitigations: ['Concurrency caps below quota', 'Token bucket in front of the provider', 'Second provider for overflow'],
    defaultProbability: 0.02,
  })

